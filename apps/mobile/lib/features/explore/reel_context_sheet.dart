// ── Words the dictionary knows ──────────────────────────────────────────────

/// One word from a caption with its published dictionary senses.
class ReelWordMatch {
  const ReelWordMatch({required this.word, required this.senses});

  /// The word as it was written in the caption.
  final String word;
  final List<DictionaryEntry> senses;
}

/// Words in [text] the published dictionary knows, in reading order, once
/// each, at most [limit] of them.
///
/// The same index the Community feed uses to make words tappable — see
/// `dictionaryIndexProvider` — so a word that teaches in a post teaches in a
/// reel too, and the two can never disagree about what it means.
List<ReelWordMatch> reelWordMatches(
  String text,
  Map<String, List<DictionaryEntry>> index, {
  int limit = 12,
}) {
  if (text.trim().isEmpty || index.isEmpty) return const [];
  final seen = <String>{};
  final matches = <ReelWordMatch>[];
  for (final match in wordPattern.allMatches(text)) {
    final written = match.group(0) ?? '';
    final key = normaliseWord(written);
    if (key.length < 2 || !seen.add(key)) continue;
    final senses = index[key];
    if (senses == null || senses.isEmpty) continue;
    matches.add(ReelWordMatch(word: written, senses: senses));
    if (matches.length >= limit) break;
  }
  return matches;
}

/// The text of a reel worth reading for words: its title and its caption.
String reelReadableText(Reel reel) => [
  reel.title,
  if (reel.caption.trim() != reel.title.trim()) reel.caption,
].where((part) => part.trim().isNotEmpty).join('\n');

/// Whether [reel] has anything a translation panel could show.
bool reelHasTranslation(Reel reel, Map<String, List<DictionaryEntry>> index) =>
    !reel.isSponsored &&
    (reel.englishSummary.trim().isNotEmpty ||
        reel.translations.isNotEmpty ||
        reelWordMatches(reelReadableText(reel), index, limit: 1).isNotEmpty);

// ── Where a piece of information came from ──────────────────────────────────

/// The four kinds of source the Context sheet speaks from, kept visually
/// distinct so a member can always tell a creator's own words from a reviewed
/// fact from a machine's guess.
enum ReelContextSource {
  /// Written by whoever published the piece.
  creator('Creator-provided', Icons.person_outline_rounded),

  /// Approved by a person on the Indigen World review desk.
  reviewed(
    'Reviewed by the Indigen World review desk',
    Icons.verified_outlined,
  ),

  /// From the published dictionary, which the community compiles and reviews.
  dictionary('Community-reviewed dictionary', Icons.menu_book_outlined),

  /// Generated by Kawuri. Never presented as fact.
  ai('AI-generated · not verified', Icons.auto_awesome_outlined);

  const ReelContextSource(this.label, this.icon);

  final String label;
  final IconData icon;
}

class ReelSourceTag extends StatelessWidget {
  const ReelSourceTag({required this.source, super.key});

  final ReelContextSource source;

  @override
  Widget build(BuildContext context) {
    final brand = context.brand;
    final colour = switch (source) {
      ReelContextSource.creator => brand.mutedInk,
      ReelContextSource.reviewed => brand.success,
      ReelContextSource.dictionary => brand.accent,
      ReelContextSource.ai => brand.gold,
    };
    return Semantics(
      label: 'Source: ${source.label}',
      excludeSemantics: true,
      child: Container(
        padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
        decoration: BoxDecoration(
          borderRadius: BorderRadius.circular(999),
          border: Border.all(color: colour.withValues(alpha: 0.6)),
          color: colour.withValues(alpha: 0.1),
        ),
        child: Row(
          mainAxisSize: MainAxisSize.min,
          children: [
            Icon(source.icon, size: 12, color: colour),
            const SizedBox(width: 4),
            Flexible(
              child: Text(
                source.label,
                style: TextStyle(
                  color: colour,
                  fontSize: 11,
                  fontWeight: FontWeight.w700,
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }
}

// ── The Context sheet ───────────────────────────────────────────────────────

/// The three resting heights of the Context sheet: a glance, half the screen,
/// and nearly all of it.
const double kContextCollapsed = 0.28;
const double kContextMedium = 0.55;
const double kContextExpanded = 0.94;

/// Past this, the sheet covers enough of the reel that it pauses.
const double kContextPauseExtent = 0.7;

/// Opens the Context sheet over the reel.
///
/// A modal route over the feed rather than a navigation away from it, so the
/// member's place — the reel, and where they were in it — is exactly where
/// they left it when the sheet closes. [onExtentChanged] reports the sheet's
/// height as it is dragged, which is how the feed knows to pause once the
/// sheet is covering most of the frame.
Future<void> showReelContextSheet(
  BuildContext context, {
  required Reel reel,
  required String creatorName,
  required String handle,
  required VoidCallback onOpenCreator,
  VoidCallback? onOpenCommunity,
  VoidCallback? onPronunciationPlay,
  VoidCallback? onTranslationOpen,
  ValueChanged<double>? onExtentChanged,
  bool startExpanded = false,
}) => showModalBottomSheet<void>(
  context: context,
  isScrollControlled: true,
  useSafeArea: true,
  backgroundColor: Colors.transparent,
  barrierColor: Colors.black26,
  // The sheet draws its own handle on its own surface; the theme's would float
  // above it over the video.
  showDragHandle: false,
  builder: (sheetContext) => NightTheme(
    child: NotificationListener<DraggableScrollableNotification>(
      onNotification: (notification) {
        onExtentChanged?.call(notification.extent);
        return false;
      },
      child: DraggableScrollableSheet(
        expand: false,
        initialChildSize: startExpanded ? kContextExpanded : kContextMedium,
        minChildSize: kContextCollapsed,
        maxChildSize: kContextExpanded,
        snap: true,
        snapSizes: const [kContextMedium],
        builder: (context, scrollController) => ReelContextBody(
          reel: reel,
          creatorName: creatorName,
          handle: handle,
          scrollController: scrollController,
          onOpenCreator: () {
            Navigator.of(sheetContext).pop();
            onOpenCreator();
          },
          onOpenCommunity: onOpenCommunity == null
              ? null
              : () {
                  Navigator.of(sheetContext).pop();
                  onOpenCommunity();
                },
          onPronunciationPlay: onPronunciationPlay,
          onTranslationOpen: onTranslationOpen,
        ),
      ),
    ),
  ),
);

class ReelContextBody extends ConsumerWidget {
  const ReelContextBody({
    required this.reel,
    required this.creatorName,
    required this.handle,
    required this.onOpenCreator,
    this.scrollController,
    this.onOpenCommunity,
    this.onPronunciationPlay,
    this.onTranslationOpen,
    super.key,
  });

  final Reel reel;
  final String creatorName;
  final String handle;
  final ScrollController? scrollController;
  final VoidCallback onOpenCreator;
  final VoidCallback? onOpenCommunity;
  final VoidCallback? onPronunciationPlay;
  final VoidCallback? onTranslationOpen;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final brand = context.brand;
    final index = ref.watch(dictionaryIndexProvider);
    final words = reelWordMatches(reelReadableText(reel), index);
    final space = reel.community == null
        ? null
        : ref.watch(communitySpaceProvider(reel.community!.id)).asData?.value;
    final creatorSource = reel.isReviewed
        ? ReelContextSource.reviewed
        : ReelContextSource.creator;
    final hasMeaning =
        reel.englishSummary.trim().isNotEmpty || reel.translations.isNotEmpty;
    final hasCulture = reel.culturalNotes.trim().isNotEmpty;
    final hasAnyContext = hasMeaning || hasCulture || words.isNotEmpty;

    return DecoratedBox(
      decoration: BoxDecoration(
        color: brand.surfaceElevated,
        borderRadius: const BorderRadius.vertical(top: Radius.circular(24)),
        border: Border(top: BorderSide(color: brand.border)),
      ),
      child: ListView(
        controller: scrollController,
        padding: const EdgeInsets.fromLTRB(20, 0, 20, 32),
        children: [
          const _SheetHandle(),
          Text(
            [
              reel.categoryLabel,
              if (reel.languageLabel.isNotEmpty)
                reel.languageLabel.toUpperCase(),
            ].join(' · '),
            style: TextStyle(
              color: brand.gold,
              fontSize: 11,
              fontWeight: FontWeight.w800,
              letterSpacing: 1.1,
            ),
          ),
          // A published piece has a title of its own. A community post has
          // only what its author wrote, which is read as words, not set as a
          // headline.
          if (reel.title.trim().isNotEmpty &&
              reel.title.trim() != reel.caption.trim()) ...[
            const SizedBox(height: 6),
            Text(
              reel.title.trim(),
              style: TextStyle(
                color: brand.ink,
                fontSize: 20,
                height: 1.25,
                fontWeight: FontWeight.w800,
              ),
            ),
          ],
          const SizedBox(height: 4),
          Text(
            handle.isEmpty ? 'By $creatorName' : 'By $creatorName · @$handle',
            style: TextStyle(color: brand.mutedInk, fontSize: 13.5),
          ),
          if (reel.caption.trim().isNotEmpty) ...[
            const SizedBox(height: 10),
            _Body(reel.caption.trim()),
          ],
          const SizedBox(height: 12),
          Wrap(
            spacing: 6,
            runSpacing: 6,
            children: [
              _Fact(icon: Icons.source_outlined, text: reel.sourceLabel),
              if (reel.languageLabel.isNotEmpty)
                _Fact(icon: Icons.translate_rounded, text: reel.languageLabel),
              if (reel.dialect.trim().isNotEmpty)
                _Fact(
                  icon: Icons.record_voice_over_outlined,
                  text: reel.dialect.trim(),
                ),
              if (reel.community case final community?)
                _Fact(
                  icon: Icons.diversity_3_rounded,
                  text: space?.name ?? community.name,
                ),
              if (space != null && space.location.trim().isNotEmpty)
                _Fact(icon: Icons.place_outlined, text: space.location.trim()),
            ],
          ),
          if (reel.ageRating == '13+') ...[
            const SizedBox(height: 16),
            const _Notice(
              icon: Icons.info_outline_rounded,
              title: 'Content note',
              body:
                  'The creator declared that this piece involves minors. '
                  'Please share it with care.',
            ),
          ],
          if (!hasAnyContext) ...[
            const SizedBox(height: 16),
            const _Notice(
              icon: Icons.menu_book_outlined,
              title: 'No context has been added yet',
              body:
                  'The creator has not written a translation or cultural '
                  'notes for this piece, and none of its words are in the '
                  'dictionary yet. Its attribution is below.',
            ),
          ],
          if (hasMeaning) ...[
            _Section(
              title: 'Meaning and translation',
              source: creatorSource,
              children: [
                if (reel.englishSummary.trim().isNotEmpty)
                  _Body(reel.englishSummary.trim()),
                if (reel.translations.isNotEmpty) ...[
                  if (reel.englishSummary.trim().isNotEmpty)
                    const SizedBox(height: 8),
                  for (final meaning in reel.translations) _Bullet(meaning),
                ],
              ],
            ),
          ],
          if (words.isNotEmpty)
            _Section(
              title: 'Words in this post',
              source: ReelContextSource.dictionary,
              children: [
                for (final match in words)
                  ReelWordRow(
                    match: match,
                    onPronunciationPlay: onPronunciationPlay,
                    onOpened: onTranslationOpen,
                  ),
              ],
            ),
          if (hasCulture)
            _Section(
              title: 'Cultural context',
              source: creatorSource,
              children: [_Body(reel.culturalNotes.trim())],
            ),
          if (!reel.isSponsored)
            _Section(
              title: 'Explanation',
              source: ReelContextSource.ai,
              children: [ReelAiExplanation(reel: reel)],
            ),
          _Section(
            title: 'Source and attribution',
            children: [
              ReelAttributionDetails(
                reel: reel,
                creatorName: creatorName,
                handle: handle,
              ),
            ],
          ),
          if (!reel.isSponsored)
            _Section(
              title: 'Related',
              children: [
                _RelatedLink(
                  icon: Icons.person_outline_rounded,
                  label: 'More from $creatorName',
                  onTap: onOpenCreator,
                ),
                if (onOpenCommunity != null && reel.community != null)
                  _RelatedLink(
                    icon: Icons.diversity_3_rounded,
                    label: 'Posts in ${space?.name ?? reel.community!.name}',
                    onTap: onOpenCommunity!,
                  ),
              ],
            ),
        ],
      ),
    );
  }
}

/// Who made it, where it came from, and on what terms it is shown — the
/// provenance every Explore item carries, laid out as a list of facts.
class ReelAttributionDetails extends StatelessWidget {
  const ReelAttributionDetails({
    required this.reel,
    required this.creatorName,
    required this.handle,
    super.key,
  });

  final Reel reel;
  final String creatorName;
  final String handle;

  @override
  Widget build(BuildContext context) {
    final brand = context.brand;
    final rows = <(String, String)>[
      if (!reel.isSponsored)
        ('Creator', handle.isEmpty ? creatorName : '$creatorName (@$handle)'),
      ('Source', reel.sourceLabel),
      if (reel.sourceAttribution.trim().isNotEmpty)
        ("Creator's stated source", reel.sourceAttribution.trim()),
      if (reel.community case final community?) ('Community', community.name),
      ('Category', _sentenceCase(reel.categoryLabel)),
      if (reel.languageLabel.isNotEmpty) ('Language', reel.languageLabel),
      if (reel.createdAt case final created?)
        ('Created', formatReelDate(created)),
      if (reel.publishedAt case final published?)
        ('Published', formatReelDate(published)),
      if (reel.isLive && !reel.isCommunity && !reel.isSponsored)
        (
          'Review',
          reel.isReviewed
              ? 'Approved on the Indigen World review desk'
              : 'Published by the creator without review',
        ),
      ('Permission', reel.credit),
    ];
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        for (final (label, value) in rows)
          Padding(
            padding: const EdgeInsets.only(bottom: 9),
            child: Row(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                SizedBox(
                  width: 118,
                  child: Text(
                    label,
                    style: TextStyle(
                      color: brand.mutedInk,
                      fontSize: 12.5,
                      fontWeight: FontWeight.w700,
                    ),
                  ),
                ),
                Expanded(
                  child: Text(
                    value,
                    style: TextStyle(
                      color: brand.ink,
                      fontSize: 13.5,
                      height: 1.35,
                    ),
                  ),
                ),
              ],
            ),
          ),
      ],
    );
  }
}

