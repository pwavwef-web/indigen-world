/// Opens the translation panel: the words as written, what they mean, and the
/// words the dictionary can say aloud.
///
/// Smaller than the Context sheet and about one thing. It never pretends to be
/// a translation of the whole caption unless the creator wrote one — word by
/// word glosses are labelled as the dictionary's, and nothing is machine
/// translated here.
Future<void> showReelTranslationSheet(
  BuildContext context, {
  required Reel reel,
  VoidCallback? onPronunciationPlay,
}) => showModalBottomSheet<void>(
  context: context,
  isScrollControlled: true,
  useSafeArea: true,
  backgroundColor: Colors.transparent,
  barrierColor: Colors.black26,
  // The sheet draws its own handle on its own surface; the theme's would float
  // above it over the video.
  showDragHandle: false,
  constraints: BoxConstraints(
    maxHeight: MediaQuery.sizeOf(context).height * 0.62,
  ),
  builder: (sheetContext) => NightTheme(
    child: ReelTranslationBody(
      reel: reel,
      onPronunciationPlay: onPronunciationPlay,
    ),
  ),
);

class ReelTranslationBody extends ConsumerWidget {
  const ReelTranslationBody({
    required this.reel,
    this.onPronunciationPlay,
    super.key,
  });

  final Reel reel;
  final VoidCallback? onPronunciationPlay;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final brand = context.brand;
    final original = reelReadableText(reel);
    final words = reelWordMatches(original, ref.watch(dictionaryIndexProvider));
    final creatorSource = reel.isReviewed
        ? ReelContextSource.reviewed
        : ReelContextSource.creator;
    return DecoratedBox(
      decoration: BoxDecoration(
        color: brand.surfaceElevated,
        borderRadius: const BorderRadius.vertical(top: Radius.circular(24)),
        border: Border(top: BorderSide(color: brand.border)),
      ),
      child: ListView(
        shrinkWrap: true,
        padding: const EdgeInsets.fromLTRB(20, 0, 20, 28),
        children: [
          const _SheetHandle(),
          Text(
            'Translation',
            style: TextStyle(
              color: brand.ink,
              fontSize: 18,
              fontWeight: FontWeight.w800,
            ),
          ),
          if (original.trim().isNotEmpty) ...[
            const SizedBox(height: 10),
            Text(
              original.trim(),
              style: TextStyle(
                color: brand.mutedInk,
                fontSize: 14,
                height: 1.45,
                fontStyle: FontStyle.italic,
              ),
            ),
          ],
          if (reel.englishSummary.trim().isNotEmpty ||
              reel.translations.isNotEmpty)
            _Section(
              title: 'In English',
              source: creatorSource,
              children: [
                if (reel.englishSummary.trim().isNotEmpty)
                  _Body(reel.englishSummary.trim()),
                for (final meaning in reel.translations) _Bullet(meaning),
              ],
            ),
          if (words.isNotEmpty)
            _Section(
              title: 'Word by word',
              source: ReelContextSource.dictionary,
              children: [
                for (final match in words)
                  ReelWordRow(
                    match: match,
                    onPronunciationPlay: onPronunciationPlay,
                  ),
              ],
            ),
          if (words.isEmpty &&
              reel.englishSummary.trim().isEmpty &&
              reel.translations.isEmpty)
            const Padding(
              padding: EdgeInsets.only(top: 16),
              child: _Notice(
                icon: Icons.translate_rounded,
                title: 'No translation yet',
                body:
                    'Nobody has translated this piece, and none of its words '
                    'are in the dictionary yet.',
              ),
            ),
        ],
      ),
    );
  }
}

/// One dictionary word: what it is, what it means, and a way to hear it.
