    final brand = context.brand;
    final entry = match.senses.first;
    final more = match.senses.length - 1;
    return Padding(
      padding: const EdgeInsets.only(bottom: 6),
      child: Row(
        children: [
          Expanded(
            child: Semantics(
              button: true,
              label:
                  '${entry.headword}: ${entry.primaryTranslation}. '
                  'Open the dictionary card',
              excludeSemantics: true,
              child: InkWell(
                borderRadius: BorderRadius.circular(10),
                onTap: () {
                  onOpened?.call();
                  showWordSenses(context, match.senses);
                },
                child: Padding(
                  padding: const EdgeInsets.symmetric(vertical: 6),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text.rich(
                        TextSpan(
                          children: [
                            TextSpan(
                              text: entry.headword,
                              style: TextStyle(
                                color: brand.ink,
                                fontSize: 15.5,
                                fontWeight: FontWeight.w800,
                              ),
                            ),
                            if (entry.pronunciation.isNotEmpty)
                              TextSpan(
                                text: '  ${entry.pronunciation}',
                                style: TextStyle(
                                  color: brand.mutedInk,
                                  fontSize: 13,
                                  fontStyle: FontStyle.italic,
                                ),
                              ),
                          ],
                        ),
                      ),
                      const SizedBox(height: 2),
                      Text(
                        more > 0
                            ? '${entry.primaryTranslation} · $more more '
                                  '${more == 1 ? 'sense' : 'senses'}'
                            : entry.primaryTranslation,
                        style: TextStyle(
                          color: brand.mutedInk,
                          fontSize: 13.5,
                          height: 1.35,
                        ),
                      ),
                    ],
                  ),
                ),
              ),
            ),
          ),
          const SizedBox(width: 8),
          PronunciationButton(
            audioUrl: entry.audioUrl,
            onPlay: onPronunciationPlay,
          ),
        ],
      ),
    );
  }
}

// ── Kawuri's explanation ────────────────────────────────────────────────────

/// An explanation from Kawuri, asked for rather than shown by default.
///
/// ── Why it is behind a button, and labelled the way it is ──────────────────
/// A language model is confidently wrong about specific communities often
/// enough that its answer cannot sit beside a creator's own notes as though it
/// were the same kind of thing. So it is never generated until the member asks,
/// it is headed "AI-generated · not verified" in the same place every other
/// section names its source, and when the model cannot be reached the offline
/// guide's generic answer is not passed off in its place.
class ReelAiExplanation extends ConsumerStatefulWidget {
  const ReelAiExplanation({required this.reel, super.key});

  final Reel reel;

  @override
  ConsumerState<ReelAiExplanation> createState() => _ReelAiExplanationState();
}

enum _AiState { idle, loading, answered, unavailable }

class _ReelAiExplanationState extends ConsumerState<ReelAiExplanation> {
  var _state = _AiState.idle;
  var _answer = '';

  Future<void> _ask() async {
    setState(() => _state = _AiState.loading);
    final answer = await ref.read(kawuriServiceProvider).ask([
      KawuriMessage(
        id: 'explore-context-${widget.reel.id}',
        role: KawuriRole.you,
        text: reelExplanationPrompt(widget.reel),
        sentAt: DateTime.now(),
      ),
    ]);
    if (!mounted) return;
    setState(() {
      if (answer.fromOfflineGuide || answer.text.trim().isEmpty) {
        _state = _AiState.unavailable;
      } else {
        _state = _AiState.answered;
        _answer = answer.text.trim();
      }
    });
  }

  @override
  Widget build(BuildContext context) {
    final brand = context.brand;
    switch (_state) {
      case _AiState.idle:
        return Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              'Kawuri can suggest an explanation. It may be wrong about '
              'people, places and customs, and nobody has reviewed it.',
              style: TextStyle(
                color: brand.mutedInk,
                fontSize: 13,
                height: 1.4,
              ),
            ),
            const SizedBox(height: 10),
            OutlinedButton.icon(
              onPressed: _ask,
              icon: const Icon(Icons.auto_awesome_outlined, size: 18),
              label: const Text('Ask Kawuri to explain'),
            ),
          ],
        );
      case _AiState.loading:
        return Row(
          children: [
            SizedBox.square(
              dimension: 18,
              child: CircularProgressIndicator(
                strokeWidth: 2,
                color: brand.gold,
              ),
            ),
            const SizedBox(width: 10),
            Text(
              'Kawuri is thinking…',
              style: TextStyle(color: brand.mutedInk, fontSize: 13),
            ),
          ],
        );
      case _AiState.unavailable:
        return Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              'Kawuri could not be reached, so there is no explanation to '
              'show. Nothing has been guessed in its place.',
              style: TextStyle(
                color: brand.mutedInk,
                fontSize: 13,
                height: 1.4,
              ),
            ),
            TextButton(onPressed: _ask, child: const Text('Try again')),
          ],
        );
      case _AiState.answered:
        return Container(
          width: double.infinity,
          padding: const EdgeInsets.all(12),
          decoration: BoxDecoration(
            borderRadius: BorderRadius.circular(14),
            border: Border.all(color: brand.gold.withValues(alpha: 0.45)),
            color: brand.gold.withValues(alpha: 0.06),
          ),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              _Body(_answer),
              const SizedBox(height: 8),
              Text(
                'Generated by AI from this post’s own text. Check with the '
                'creator or the community before relying on it.',
                style: TextStyle(
                  color: brand.mutedInk,
                  fontSize: 12,
                  height: 1.35,
                  fontStyle: FontStyle.italic,
                ),
              ),
            ],
          ),
        );
    }
  }
}

/// What Kawuri is asked. Built only from what the post itself says, with the
/// instruction to say so when it is unsure rather than fill the gap.
String reelExplanationPrompt(Reel reel) {
  final lines = <String>[
    'Explain this Indigen World Explore post for a learner in 4 short '
        'sentences or fewer. Use only what is written below and general, '
        'well-established knowledge. If you are not sure about a specific '
        'community, custom or meaning, say that you are not sure instead of '
        'guessing.',
    if (reel.title.trim().isNotEmpty) 'Title: ${reel.title.trim()}',
    if (reel.caption.trim().isNotEmpty &&
        reel.caption.trim() != reel.title.trim())
      'Caption: ${reel.caption.trim()}',
    'Category: ${_sentenceCase(reel.categoryLabel)}',
    if (reel.languageLabel.isNotEmpty) 'Language: ${reel.languageLabel}',
    if (reel.dialect.trim().isNotEmpty) 'Dialect: ${reel.dialect.trim()}',
    if (reel.community != null) 'Community: ${reel.community!.name}',
    if (reel.culturalNotes.trim().isNotEmpty)
      "Creator's cultural notes: ${reel.culturalNotes.trim()}",
    if (reel.englishSummary.trim().isNotEmpty)
      "Creator's English summary: ${reel.englishSummary.trim()}",
  ];
  return lines.join('\n');
}

